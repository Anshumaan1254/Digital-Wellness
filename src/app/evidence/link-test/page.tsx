import type { Metadata } from "next";
import { PageHeader, Section } from "@/components/site/PageHeader";
import { EvidenceNav } from "@/components/site/EvidenceNav";
import record from "@/data/link-test-record.json";
import { cn } from "@/lib/utils";

export const metadata: Metadata = { title: "Link test record" };

type Row = {
  url: string;
  usedIn: string[];
  status: number;
  result: string;
  checkedAt: string;
  browserStatus?: number;
  error?: string;
};

const RESULT: Record<string, { label: string; cls: string }> = {
  pass: { label: "Pass", cls: "bg-[#173a36] text-[#a6e6da]" },
  "pass-in-browser": { label: "Pass (in browser)", cls: "bg-[#173a36] text-[#a6e6da]" },
  "blocked-automated": { label: "Blocked to scripts", cls: "bg-[#3e2f24] text-[#f6d3b3]" },
  fail: { label: "Fail", cls: "bg-[#4a2326] text-[#f2a7a0]" },
};

export default function LinkTestPage() {
  const s = record.summary as typeof record.summary & { external: { passInBrowser?: number } };
  const rows = record.external as Row[];
  const internal = record.internal as { url: string; status: number; result: string }[];
  const order = ["fail", "blocked-automated", "pass-in-browser", "pass"];
  const sorted = [...rows].sort((a, b) => order.indexOf(a.result) - order.indexOf(b.result));

  return (
    <>
      <PageHeader eyebrow="Project evidence" title="Link test record">
        Generated by <code className="rounded bg-white/10 px-1.5 py-0.5 text-sm">scripts/check-links.mjs</code> on{" "}
        {s.generatedAt.slice(0, 16).replace("T", " ")} UTC. Each link is requested directly; anything that fails is
        opened again in a real browser, the way a student would click it.
      </PageHeader>
      <EvidenceNav current="/evidence/link-test" />
      <Section>
        <dl className="grid gap-4 sm:grid-cols-2 lg:grid-cols-5">
          {[
            ["External links", s.external.total],
            ["Passed", s.external.pass],
            ["Passed in a browser", s.external.passInBrowser ?? 0],
            ["Blocked to scripts", s.external.blocked],
            ["Failed", s.external.fail],
          ].map(([k, v]) => (
            <div key={k} className="rounded-3xl border border-border bg-card p-5">
              <dt className="text-sm text-muted-foreground">{k}</dt>
              <dd className="font-serif text-4xl text-dawn">{v}</dd>
            </div>
          ))}
        </dl>
        <p className="mt-5 max-w-3xl text-sm text-muted-foreground">
          &ldquo;Blocked to scripts&rdquo; means the website refused an automated request (often a bot check) even in a
          browser, so we could not prove the link from a script — these need a quick manual click before submission.
        </p>
        {internal.length > 0 && (
          <p className="mt-3 text-sm">
            Internal pages crawled: <strong>{internal.length}</strong>, loaded successfully:{" "}
            <strong>{internal.filter((p) => p.result === "pass").length}</strong>.
          </p>
        )}
      </Section>
      <Section title="Every external link">
        <div className="overflow-x-auto rounded-3xl border border-border" role="region" aria-label="Link test table, scrolls sideways" tabIndex={0}>
          <table className="w-full min-w-[900px] text-left text-sm">
            <caption className="sr-only">Result of testing each external link</caption>
            <thead className="bg-[#13273a] text-xs uppercase tracking-wider text-mist">
              <tr>
                <th scope="col" className="px-4 py-3">Result</th>
                <th scope="col" className="px-4 py-3">Link</th>
                <th scope="col" className="px-4 py-3">Used in</th>
                <th scope="col" className="px-4 py-3">HTTP</th>
                <th scope="col" className="px-4 py-3">Checked (UTC)</th>
              </tr>
            </thead>
            <tbody>
              {sorted.map((r) => (
                <tr key={r.url} className="border-t border-border align-top">
                  <td className="px-4 py-3">
                    <span className={cn("whitespace-nowrap rounded-full px-2.5 py-1 text-xs", RESULT[r.result]?.cls)}>{RESULT[r.result]?.label ?? r.result}</span>
                  </td>
                  <th scope="row" className="max-w-[380px] break-all px-4 py-3 font-normal">
                    <a href={r.url} rel="noopener" className="text-lake underline underline-offset-4 hover:text-dawn">
                      {r.url}
                    </a>
                  </th>
                  <td className="px-4 py-3 text-muted-foreground">{r.usedIn.join("; ")}</td>
                  <td className="px-4 py-3">
                    {r.status || r.error}
                    {r.browserStatus ? ` → ${r.browserStatus} in browser` : ""}
                  </td>
                  <td className="whitespace-nowrap px-4 py-3">{r.checkedAt.slice(0, 16).replace("T", " ")}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </Section>
    </>
  );
}
